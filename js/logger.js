'use strict';

/* ==========================================================
   Logger Class
   ========================================================== */

window.CTM = window.CTM || {};

class Logger {

    #initialized = false;

    constructor() {

        if (CTM.Logger) {
            return CTM.Logger;
        }

    }

    /* ======================================================
       Initialize
       ====================================================== */

    init() {

        if (this.#initialized) {
            return;
        }

        this.#initialized = true;

        this.info(
            `${CTM.Config.APP.NAME} v${CTM.Config.APP.VERSION} initialized.`
        );

    }

    /* ======================================================
       Information
       ====================================================== */

    info(message, ...data) {

        console.info(

            `[INFO]`,

            message,

            ...data

        );

    }

    /* ======================================================
       Warning
       ====================================================== */

    warn(message, ...data) {

        console.warn(

            `[WARN]`,

            message,

            ...data

        );

    }

    /* ======================================================
       Error
       ====================================================== */

    error(message, ...data) {

        console.error(

            `[ERROR]`,

            message,

            ...data

        );

    }

    /* ======================================================
       Debug
       ====================================================== */

    debug(message, ...data) {

        if (!CTM.Config.FEATURES.DEBUG) {
            return;
        }

        console.debug(

            `[DEBUG]`,

            message,

            ...data

        );

    }

    /* ======================================================
       Group
       ====================================================== */

    group(title) {

        console.group(title);

    }

    /* ======================================================
       Group End
       ====================================================== */

    groupEnd() {

        console.groupEnd();

    }

    /* ======================================================
       Timer Start
       ====================================================== */

    time(label) {

        console.time(label);

    }

    /* ======================================================
       Timer End
       ====================================================== */

    timeEnd(label) {

        console.timeEnd(label);

    }

    /* ======================================================
       Destroy
       ====================================================== */

    destroy() {

        this.#initialized = false;

    }

}

/* ==========================================================
   Singleton
   ========================================================== */

CTM.Logger = Object.freeze(

    new Logger()

);

